"""data/terrain.json + named points of data/castle_layout.json + fitted parameters of data/fit_r7.json -> web/data.js
(embedded, works from file:// and htmlpreview).
r7b: also ships the measured-data fit (terrace surfaces T.P., ishigaki batter percentiles) and the water bodies
(one polygon per OSM moat/river way, with its level: PLATEAU-measured when tools/fit_terrain.py found inclined ishigaki
faces on its shore, otherwise an estimate = shoreline DEM5A 5th percentile - FREEBOARD, flagged est=True)."""
import json, os, sys
import numpy as np
from shapely.geometry import Polygon
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import geodata as G
FREEBOARD = 0.5   # estimate only (no measurement): unmeasured water surface sits this far below its lowest bank (5th pct)
T = json.load(open(os.path.join(ROOT, 'data', 'terrain.json')))
L = json.load(open(os.path.join(ROOT, 'data', 'castle_layout.json')))
F = json.load(open(os.path.join(ROOT, 'data', 'fit_r7.json')))
pts = {}
for p in L['points']:
    pts.setdefault(p['name'], [round(p['xy'][0], 2), round(p['xy'][1], 2)])
T['points'] = pts
meas = {}
for w in F['water']:
    if w['level'] is None: continue
    for m in w['members']: meas[m] = (w['level'], w['name'])
dem = G.DEM(); water = []
for w in L['moats'] + L['rivers']:
    if len(w['pts']) <= 3: continue
    p = Polygon(w['pts']).buffer(0)
    if p.geom_type != 'Polygon': p = max(p.geoms, key=lambda g: g.area)
    r = p.buffer(6).exterior; q = [r.interpolate(t, normalized=True) for t in np.linspace(0, 1, 600)]
    zs = dem(np.array([a.x for a in q]), np.array([a.y for a in q])); zs = zs[~np.isnan(zs)]
    shore = float(np.percentile(zs, 5)) if len(zs) else None
    if w['id'] in meas: lvl, src = meas[w['id']][0], 'PLATEAU'
    else: lvl, src = round(shore - FREEBOARD, 2), 'est'
    water.append(dict(id=w['id'], name=w.get('name') or meas.get(w['id'], (0, ''))[1] or str(w['id']), level=lvl, src=src, shore=round(shore, 2) if shore is not None else None,
                      pts=[[round(x, 1), round(y, 1)] for x, y in list(p.simplify(0.5).exterior.coords)[:-1]]))
T['fit'] = dict(surfaces=F['surfaces'], batter=F['ishigaki']['batter_pct'], water=water, changed=F.get('changed_areas', []))
s = json.dumps(T, ensure_ascii=False, separators=(',', ':'))
open(os.path.join(ROOT, 'web', 'data.js'), 'w').write(
    '// generated by tools/make_webdata.py from data/terrain.json (+ named points of castle_layout.json, + data/fit_r7.json). Map data (c) OpenStreetMap contributors, ODbL; elevations GSI DEM5A; ishigaki/water PLATEAU (MLIT).\n'
    '(typeof window!=="undefined"?window:globalThis).CASTLE_DATA=' + s + ';\n')
print('web/data.js', len(s), 'bytes'); print([(w['name'], w['level'], w['src']) for w in water])
