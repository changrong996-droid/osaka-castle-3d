"""data/terrain.json + named points of data/castle_layout.json -> web/data.js (embedded, works from file:// and htmlpreview)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = json.load(open(os.path.join(ROOT, 'data', 'terrain.json')))
L = json.load(open(os.path.join(ROOT, 'data', 'castle_layout.json')))
pts = {}
for p in L['points']:
    pts.setdefault(p['name'], [round(p['xy'][0], 2), round(p['xy'][1], 2)])
T['points'] = pts
s = json.dumps(T, ensure_ascii=False, separators=(',', ':'))
open(os.path.join(ROOT, 'web', 'data.js'), 'w').write(
    '// generated by tools/make_webdata.py from data/terrain.json (+ named points of castle_layout.json). Map data (c) OpenStreetMap contributors, ODbL.\n'
    '(typeof window!=="undefined"?window:globalThis).CASTLE_DATA=' + s + ';\n')
print('web/data.js', len(s), 'bytes')
